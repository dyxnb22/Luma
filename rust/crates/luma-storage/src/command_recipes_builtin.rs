fn param_text(
    id: &str,
    label: &str,
    required: bool,
    default: Option<&str>,
) -> luma_domain::RecipeParameter {
    luma_domain::RecipeParameter {
        id: id.into(),
        label: label.into(),
        description: String::new(),
        kind: luma_domain::RecipeParameterKind::Text,
        required,
        default: default.map(str::to_string),
        choices: vec![],
        min: None,
        max: None,
        pattern: None,
        max_length: Some(256),
    }
}

fn param_integer(
    id: &str,
    label: &str,
    default: Option<&str>,
    min: i64,
    max: i64,
) -> luma_domain::RecipeParameter {
    luma_domain::RecipeParameter {
        id: id.into(),
        label: label.into(),
        description: String::new(),
        kind: luma_domain::RecipeParameterKind::Integer,
        required: false,
        default: default.map(str::to_string),
        choices: vec![],
        min: Some(min),
        max: Some(max),
        pattern: None,
        max_length: None,
    }
}

fn param_path(
    id: &str,
    label: &str,
    required: bool,
    default: Option<&str>,
) -> luma_domain::RecipeParameter {
    luma_domain::RecipeParameter {
        id: id.into(),
        label: label.into(),
        description: String::new(),
        kind: luma_domain::RecipeParameterKind::Path,
        required,
        default: default.map(str::to_string),
        choices: vec![],
        min: None,
        max: None,
        pattern: None,
        max_length: Some(1024),
    }
}
