use luma_domain::{CommandStep, Recipe, RecipeRisk, RecipeScope, RecipeVariant};

fn step(id: &str, label: &str, program: &str, args: &[&str], cwd: &str) -> CommandStep {
    CommandStep {
        id: id.into(),
        label: label.into(),
        program: program.into(),
        args: args.iter().map(|s| (*s).to_string()).collect(),
        cwd: cwd.into(),
        continue_on_error: false,
    }
}

fn git_variants(id: &str, program_args: &[&str], label: &str) -> Vec<RecipeVariant> {
    let repository = RecipeVariant {
        id: id.into(),
        description: "Git repository".into(),
        requires_files: vec![],
        requires_directories: vec![".git".into()],
        requires_commands: vec!["git".into()],
        steps: vec![step(id, label, "git", program_args, "current")],
    };
    let worktree = RecipeVariant {
        id: format!("{id}-worktree"),
        description: "Git worktree".into(),
        requires_files: vec![".git".into()],
        requires_directories: vec![],
        requires_commands: vec!["git".into()],
        steps: vec![step(id, label, "git", program_args, "current")],
    };
    vec![repository, worktree]
}

fn recipe(
    id: &str,
    title: &str,
    description: &str,
    tags: &[&str],
    scope: RecipeScope,
    variants: Vec<RecipeVariant>,
) -> Recipe {
    recipe_with_risk(
        id,
        title,
        description,
        tags,
        scope,
        RecipeRisk::Safe,
        variants,
    )
}

fn recipe_with_risk(
    id: &str,
    title: &str,
    description: &str,
    tags: &[&str],
    scope: RecipeScope,
    risk: RecipeRisk,
    variants: Vec<RecipeVariant>,
) -> Recipe {
    Recipe {
        id: id.into(),
        title: title.into(),
        description: description.into(),
        tags: tags.iter().map(|t| (*t).to_string()).collect(),
        scope,
        target: luma_domain::RecipeTarget::LocalShell,
        group: String::new(),
        risk,
        parameters: vec![],
        variants,
        enabled: true,
    }
}

#[allow(clippy::too_many_arguments)]
fn ssh_remote_recipe(
    id: &str,
    title: &str,
    description: &str,
    group: &str,
    risk: RecipeRisk,
    parameters: Vec<luma_domain::RecipeParameter>,
    program: &str,
    args: &[&str],
) -> Recipe {
    Recipe {
        id: id.into(),
        title: title.into(),
        description: description.into(),
        tags: vec!["ssh".into(), group.to_ascii_lowercase()],
        scope: RecipeScope::SshSession,
        target: luma_domain::RecipeTarget::RemoteShell,
        group: group.into(),
        risk,
        parameters,
        variants: vec![RecipeVariant {
            id: "default".into(),
            description: String::new(),
            requires_files: vec![],
            requires_directories: vec![],
            requires_commands: vec![],
            steps: vec![step(id, title, program, args, "current")],
        }],
        enabled: true,
    }
}

